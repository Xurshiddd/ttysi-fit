/// LocaleController — joriy tilni boshqaradi. Dio Accept-Language header
/// shu provider'dan o'qiydi, shuning uchun til o'zgarsa server javobi ham mos keladi.
///
/// Boshlang'ich qiymat `main()` da ombordan o'qib, override orqali beriladi —
/// aks holda tanlangan til ilova qayta ochilganda 'uz' ga qaytib ketardi.
final localeControllerProvider =
    NotifierProvider<LocaleController, Locale>(LocaleController.new);

class LocaleController extends Notifier<Locale> {
  LocaleController([this._initial = const Locale('uz')]);
  final Locale _initial;

  @override
  Locale build() => _initial;

  void setLocale(Locale locale) {
    state = locale;
    ref.read(appPrefsProvider).setLocale(locale);
  }
}

/// S — oddiy lokalizatsiya yordamchisi (backend i18n yondashuviga mos).
/// Foydalanish: `S.of(context).t('auth.signIn')`.
class S {
  S(this.locale);
  final Locale locale;

  static S of(BuildContext context) => S(Localizations.localeOf(context));

  String t(String key) {
    final lang = _messages[locale.languageCode] ?? _messages['uz']!;
    return lang[key] ?? _messages['uz']![key] ?? key;
  }
}

